from __future__ import annotations

from dataclasses import dataclass
from itertools import product

import numpy as np
import pandas as pd

from ..costs import ProportionalCostModel
from ..execution import execute_next_day, prepare_execution_market
from ..state import make_initial_state


@dataclass(frozen=True)
class BinaryTransitionTable:
    """Exact one-day log-growth transitions for positions {cash=0, stock=1}.

    Row u corresponds to the transition from close u to close u+1.  The first
    position index is the position held at the previous close; the second is
    the target position executed at the next open.  Growth multipliers are
    generated by the Phase-2 accounting primitive, so dividends, cash accrual,
    splits, gaps, and proportional costs have exactly the same semantics as a
    normal replay.
    """

    decision_dates: tuple[pd.Timestamp, ...]
    execution_dates: tuple[pd.Timestamp, ...]
    log_gross: np.ndarray  # shape (n_intervals, 2, 2)

    @property
    def n_intervals(self) -> int:
        return int(self.log_gross.shape[0])


@dataclass(frozen=True)
class OracleResult:
    log_utility: float
    actions: tuple[int, ...]
    switch_count: int
    max_switches: int
    initial_position: int
    final_position: int

    def final_wealth(self, initial_wealth: float = 1.0) -> float:
        if initial_wealth <= 0:
            raise ValueError("initial_wealth must be positive")
        return float(initial_wealth) * float(np.exp(self.log_utility))


def equivalent_switch_budget(
    n_intervals: int,
    *,
    k_per_year: int,
    annualization_days: int = 252,
) -> int:
    if n_intervals < 0:
        raise ValueError("n_intervals must be non-negative")
    if k_per_year < 0:
        raise ValueError("k_per_year must be non-negative")
    if annualization_days <= 0:
        raise ValueError("annualization_days must be positive")
    if n_intervals == 0 or k_per_year == 0:
        return 0
    return int(min(n_intervals, max(1, round(n_intervals * k_per_year / annualization_days))))


def _validate_binary_position(x: int, name: str) -> int:
    x = int(x)
    if x not in (0, 1):
        raise ValueError(f"{name} must be 0 or 1")
    return x


def build_binary_transition_table(
    asset_market: pd.DataFrame,
    *,
    cost_bps_per_side: float,
) -> BinaryTransitionTable:
    market = prepare_execution_market(asset_market)
    if len(market) < 2:
        raise ValueError("At least two market rows are required")

    n = len(market) - 1
    log_gross = np.empty((n, 2, 2), dtype=float)
    cost_model = ProportionalCostModel.from_bps(cost_bps_per_side)
    decision_dates: list[pd.Timestamp] = []
    execution_dates: list[pd.Timestamp] = []

    for u in range(n):
        prev = market.iloc[u]
        row = market.iloc[u + 1]
        decision_dates.append(pd.Timestamp(prev["date"]).normalize())
        execution_dates.append(pd.Timestamp(row["date"]).normalize())
        for prev_pos in (0, 1):
            state = make_initial_state(
                date=prev["date"],
                asset_id=str(prev["asset_id"]),
                close_price=float(prev["close"]),
                initial_wealth=1.0,
                initial_exposure=float(prev_pos),
            )
            for new_pos in (0, 1):
                step = execute_next_day(
                    state=state,
                    previous_row=prev,
                    row=row,
                    target_exposure=float(new_pos),
                    cost_model=cost_model,
                )
                wealth = float(step.ledger_row["wealth_close"])
                if not np.isfinite(wealth) or wealth <= 0.0:
                    raise ValueError("Oracle transition produced non-positive wealth")
                log_gross[u, prev_pos, new_pos] = float(np.log(wealth))

    return BinaryTransitionTable(
        decision_dates=tuple(decision_dates),
        execution_dates=tuple(execution_dates),
        log_gross=log_gross,
    )


def solve_bounded_switch_from_transitions(
    transitions: BinaryTransitionTable,
    *,
    max_switches: int,
    initial_position: int = 0,
    forced_first_action: int | None = None,
) -> OracleResult:
    """Solve the clairvoyant binary-position problem by exact dynamic programming."""
    initial_position = _validate_binary_position(initial_position, "initial_position")
    if max_switches < 0:
        raise ValueError("max_switches must be non-negative")
    kmax = min(int(max_switches), transitions.n_intervals)
    if forced_first_action is not None:
        forced_first_action = _validate_binary_position(forced_first_action, "forced_first_action")
    n = transitions.n_intervals
    if n == 0:
        return OracleResult(0.0, tuple(), 0, kmax, initial_position, initial_position)

    neg_inf = -np.inf
    dp = np.full((kmax + 1, 2), neg_inf, dtype=float)
    dp[0, initial_position] = 0.0
    parent_pos = np.full((n, kmax + 1, 2), -1, dtype=np.int8)
    parent_k = np.full((n, kmax + 1, 2), -1, dtype=np.int32)

    for u in range(n):
        lg = transitions.log_gross[u]
        newdp = np.full_like(dp, neg_inf)
        for new_pos in (0, 1):
            if u == 0 and forced_first_action is not None and new_pos != forced_first_action:
                continue

            # Stay in the same position: switch count unchanged.
            stay = dp[:, new_pos] + lg[new_pos, new_pos]
            newdp[:, new_pos] = stay
            parent_pos[u, :, new_pos] = new_pos
            parent_k[u, :, new_pos] = np.arange(kmax + 1, dtype=np.int32)

            # Switch from the other position: consume one switch.
            if kmax >= 1:
                other = 1 - new_pos
                switched = dp[:-1, other] + lg[other, new_pos]
                incumbent = newdp[1:, new_pos]
                better = switched > incumbent + 1e-15
                if np.any(better):
                    idx = np.nonzero(better)[0] + 1
                    newdp[idx, new_pos] = switched[better]
                    parent_pos[u, idx, new_pos] = other
                    parent_k[u, idx, new_pos] = idx - 1
        dp = newdp

    flat = int(np.argmax(dp))
    end_k, end_pos = np.unravel_index(flat, dp.shape)
    best = float(dp[end_k, end_pos])
    if not np.isfinite(best):
        raise ValueError("No feasible oracle path under supplied switch constraint")

    actions = [0] * n
    k = int(end_k)
    pos = int(end_pos)
    for u in range(n - 1, -1, -1):
        actions[u] = pos
        pp = int(parent_pos[u, k, pos])
        pk = int(parent_k[u, k, pos])
        if pp < 0 or pk < 0:
            raise AssertionError("Oracle backtracking encountered invalid parent")
        pos, k = pp, pk

    switches = 0
    prev = initial_position
    for action in actions:
        switches += int(action != prev)
        prev = action
    if switches > kmax:
        raise AssertionError("Oracle path violates switch budget")
    if forced_first_action is not None and actions[0] != forced_first_action:
        raise AssertionError("Oracle path violates forced first action")

    return OracleResult(
        log_utility=best,
        actions=tuple(int(x) for x in actions),
        switch_count=int(switches),
        max_switches=int(kmax),
        initial_position=initial_position,
        final_position=int(actions[-1]),
    )


def solve_bounded_switch_oracle(
    asset_market: pd.DataFrame,
    *,
    max_switches: int,
    initial_position: int = 0,
    cost_bps_per_side: float = 5.0,
    forced_first_action: int | None = None,
) -> tuple[OracleResult, BinaryTransitionTable]:
    transitions = build_binary_transition_table(
        asset_market,
        cost_bps_per_side=cost_bps_per_side,
    )
    result = solve_bounded_switch_from_transitions(
        transitions,
        max_switches=max_switches,
        initial_position=initial_position,
        forced_first_action=forced_first_action,
    )
    return result, transitions


def brute_force_bounded_switch(
    transitions: BinaryTransitionTable,
    *,
    max_switches: int,
    initial_position: int = 0,
    forced_first_action: int | None = None,
    max_intervals: int = 20,
) -> OracleResult:
    """Exact enumeration used only for small-path validation of the DP."""
    initial_position = _validate_binary_position(initial_position, "initial_position")
    if max_switches < 0:
        raise ValueError("max_switches must be non-negative")
    if transitions.n_intervals > max_intervals:
        raise ValueError("brute_force_bounded_switch is restricted to small toy paths")
    if forced_first_action is not None:
        forced_first_action = _validate_binary_position(forced_first_action, "forced_first_action")

    best_value = -np.inf
    best_actions: tuple[int, ...] | None = None
    best_switches = 0
    for actions in product((0, 1), repeat=transitions.n_intervals):
        if forced_first_action is not None and actions and actions[0] != forced_first_action:
            continue
        prev = initial_position
        switches = 0
        value = 0.0
        feasible = True
        for u, action in enumerate(actions):
            switches += int(action != prev)
            if switches > max_switches:
                feasible = False
                break
            value += float(transitions.log_gross[u, prev, action])
            prev = action
        if feasible and value > best_value + 1e-15:
            best_value = value
            best_actions = tuple(int(x) for x in actions)
            best_switches = switches

    if best_actions is None:
        raise ValueError("No feasible brute-force oracle path")
    return OracleResult(
        log_utility=float(best_value),
        actions=best_actions,
        switch_count=int(best_switches),
        max_switches=min(int(max_switches), transitions.n_intervals),
        initial_position=initial_position,
        final_position=int(best_actions[-1]) if best_actions else initial_position,
    )


def oracle_actions_frame(
    transitions: BinaryTransitionTable,
    result: OracleResult,
    *,
    asset_id: str,
) -> pd.DataFrame:
    if len(result.actions) != transitions.n_intervals:
        raise ValueError("Oracle action length does not match transition table")
    rows: list[dict] = []
    prev = result.initial_position
    for u, action in enumerate(result.actions):
        rows.append({
            "asset_id": str(asset_id),
            "decision_date": transitions.decision_dates[u],
            "execution_date": transitions.execution_dates[u],
            "previous_position": int(prev),
            "oracle_action": int(action),
            "switched": bool(action != prev),
            "transition_log_gross": float(transitions.log_gross[u, prev, action]),
        })
        prev = action
    return pd.DataFrame(rows)
